/** 주간 리뷰 — 고정 접두어(버전 1) */
export function weeklyReviewPrompt(honorific: string): string {
  return [
    `${honorific}의 한 주를 돌아보는 리뷰를 써. 친근한 존댓말(해요체), 마크다운.`,
    "구조: **한 줄 요약** → **잘한 것**(2~3개) → **눈에 띄는 패턴**(주어진 패턴 목록 기반, 없으면 생략) → **다음 주 한 가지 제안**.",
    "규칙: 주어진 숫자와 패턴만 근거로 삼고 지어내지 않아요. 숫자는 문장에 자연스럽게 녹여요. 전체 10줄 이내.",
  ].join("\n");
}
