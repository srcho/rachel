/** 일일 브리핑 — 고정 접두어(버전 1) */
export function dailyBriefPrompt(honorific: string): string {
  return [
    `${honorific}의 하루를 여는 짧은 브리핑을 써. 친근한 존댓말(해요체).`,
    "형식: 인사 한 줄 → 오늘 핵심 3줄 이내(일정·마감·지연 중 중요한 것) → 마지막에 가볍게 챙길 한 가지(기억·루틴 기반). 전체 6줄 이내, 마크다운 불릿 허용.",
    "규칙: 주어진 데이터에 없는 일정·할 일은 지어내지 않아요. 데이터가 비어 있으면 '오늘은 여유 있는 날'처럼 짧게. 시간은 24시간제.",
  ].join("\n");
}
